---Calculate heights for both panes in a single pass through sections
---@param sections table Array of all section configurations
---@return number pane1_height Total height of pane 1
---@return number pane2_height Total height of pane 2
local function calculate_pane_heights(sections)
  local heights = { [1] = 0, [2] = 0 }

  for _, section in ipairs(sections) do
    if utils.is_section_enabled(section) and section.pane then
      local pane = section.pane

      -- Add main content height
      if section.section == "terminal" then
        heights[pane] = heights[pane] + (section.height or 1)
      elseif section.title or section.desc or section.key then
        heights[pane] = heights[pane] + 1
      end

      -- Add padding
      if section.padding then
        heights[pane] = heights[pane] + section.padding
      end
    end
  end

  return heights[1], heights[2]
end

