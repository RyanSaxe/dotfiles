-- POKEMON ENV FILE EXPORT
-- Exports pokemon selection and colors to ~/.cache/pokemon-colors.env
-- This allows tmux and other tools to use the same pokemon theme colors
-- ══════════════════════════════════════════════════════════════════════════════

---Export pokemon colors to env file for use by tmux and shell
---@param name string Pokemon name
---@param shiny boolean Whether shiny variant
---@param form string|nil Form variant (e.g., "mega", "alola")
---@param colors table Color data from pokemon-colors.lua
---@param background_mode string "dark" or "light"
local function export_pokemon_to_env(name, shiny, form, colors, background_mode)
  -- Get colors for the current background mode
  local mode_colors = colors[background_mode]
  if not mode_colors then
    vim.notify(
      string.format("No colors found for background mode '%s', skipping env export", background_mode),
      vim.log.levels.WARN
    )
    return
  end

  -- Resolve fallback colors to actual hex values
  -- If a color is "fallback", we use TokyoNight defaults
  local function resolve_color(color, default)
    if color == "fallback" then
      return default
    end
    return color
  end

  -- TokyoNight Night palette defaults (matching tmux.conf)
  local dim_default = "#565f89" -- gray
  local prominent_default = "#7aa2f7" -- blue
  local bright_default = "#ff9e64" -- orange

  local dim = resolve_color(mode_colors.dim, dim_default)
  local prominent = resolve_color(mode_colors.prominent, prominent_default)
  local bright = resolve_color(mode_colors.bright, bright_default)

  -- Build env file content
  local env_content = string.format(
    [[# Auto-generated by Neovim dashboard
# Pokemon colors for tmux and shell integration
# Do not edit directly - regenerated on each nvim startup

export POKEMON_NAME="%s"
export POKEMON_SHINY="%s"
export POKEMON_FORM="%s"
export POKEMON_COLOR_DIM="%s"
export POKEMON_COLOR_PROMINENT="%s"
export POKEMON_COLOR_BRIGHT="%s"
]],
    name,
    tostring(shiny),
    form or "none",
    dim,
    prominent,
    bright
  )

  -- Write to cache file
  local env_file = vim.fn.expand("~/.cache/pokemon-colors.env")
  local f = io.open(env_file, "w")
  if f then
    f:write(env_content)
    f:close()
  else
    vim.notify(string.format("Failed to write pokemon colors to %s", env_file), vim.log.levels.ERROR)
  end
end

